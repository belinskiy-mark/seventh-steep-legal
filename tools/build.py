def e(text) -> str:
    return html.escape(str(text), quote=True)


def link(from_path: str, to_path: str) -> str:
    """Relative href from the page at site path `from_path` to `to_path` (both like "uk/guides/")."""
    rel = posixpath.relpath("/" + to_path, "/" + from_path)
    return "./" if rel == "." else rel.rstrip("/") + "/"


def asset(from_path: str, name: str) -> str:
    rel = posixpath.relpath("/assets/" + name, "/" + from_path)
    return rel


