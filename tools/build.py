def grams(ml: int, per100: float) -> str:
    """Grams for a vessel, rounded to the nearest 0.5 g, half away from zero (BrewCalculator)."""
    halves = (Decimal(ml) / 100 * Decimal(str(per100)) * 2).quantize(Decimal(1), rounding=ROUND_HALF_UP)
    value = halves / 2
    return f"{value:.1f}".rstrip("0").rstrip(".")


def to_f(celsius: float) -> int:
    """Celsius to Fahrenheit, rounded half away from zero (Temperature.swift)."""
    return int((Decimal(str(celsius)) * 9 / 5 + 32).quantize(Decimal(1), rounding=ROUND_HALF_UP))


