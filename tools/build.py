# A number and its unit are joined with a no-break space, so "7,5 г" or "100 毫升" never wraps.
# CJK units have no word boundary after them, so they are listed without \b.
UNIT_RE = re.compile(r"(\d) (°C|°F|g\b|ml\b|s\b|seconds\b|г\b|мл\b|с\b|секунд\w*|克|毫升|秒|泡)")


def keep_units(text: str) -> str:
    return UNIT_RE.sub("\\1\u00a0\\2", text)


