def tea_name(p: dict, T: dict, key: str = "name") -> str:
    return p[key][T["html_lang"]]


def guide_vals(slug: str, T: dict, profiles: dict) -> dict:
    """Every number a guide text may use, taken from the app's profile, in the language's format."""
    p = profiles[GUIDE_META[slug]["profile"]]
    lo, hi = p["tempRange"]
    return {
        "temp_c": p["tempDefault"],
        "temp_f": to_f(p["tempDefault"]),
        "range_c": f"{lo}–{hi}",
        "range_f": f"{to_f(lo)}–{to_f(hi)}",
        "g100": num(grams(100, p["gramsPer100ml"]), T),
        "g150": num(grams(150, p["gramsPer100ml"]), T),
        "per100": num(p["gramsPer100ml"], T),
        "rinse": p["rinseSeconds"],
        "first": p["infusionSeconds"][0],
        "count": len(p["infusionSeconds"]),
        "step": EXTRA_STEP_SECONDS,
    }


def card_text(slug: str, T: dict, profiles: dict) -> str:
    return T["guides"][slug]["card"].format(**guide_vals(slug, T, profiles))


def tea_row(p: dict, T: dict, here: str) -> str:
    c = p["tempDefault"]
    temp = f"{c} °C · {to_f(c)} °F" if T["show_f"] else f"{c} °C"
    per100 = T["units"]["per100"].format(g=num(grams(100, p["gramsPer100ml"]), T))
    inner = (
        f'{cup(p["liquorColor"])}'
        f'<div class="tea-main"><div class="tea-name">{e(tea_name(p, T))}</div>'
        f'<div class="tea-sub">{e(tea_name(p, T, "subtitle"))}</div></div>'
        f'<div class="tea-nums">{temp}<span>{e(per100)}</span></div>'
    )
    slug = GUIDE_BY_PROFILE.get(p["id"])
    if slug:
        aria = T["home"]["guide_aria"].format(name=tea_name(p, T))
        return f'<li><a class="tea" href="{link(here, T["prefix"] + "guides/" + slug + "/")}" aria-label="{e(aria)}">{inner}</a></li>'
    return f'<li><div class="tea">{inner}</div></li>'


