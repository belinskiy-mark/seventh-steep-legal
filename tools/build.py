def grams(ml: int, per100: float) -> str:
    """Grams for a vessel, rounded to the nearest 0.5 g, half away from zero (BrewCalculator)."""
    halves = (Decimal(ml) / 100 * Decimal(str(per100)) * 2).quantize(Decimal(1), rounding=ROUND_HALF_UP)
    value = halves / 2
    return f"{value:.1f}".rstrip("0").rstrip(".")


def to_f(celsius: float) -> int:
    """Celsius to Fahrenheit, rounded half away from zero (Temperature.swift)."""
    return int((Decimal(str(celsius)) * 9 / 5 + 32).quantize(Decimal(1), rounding=ROUND_HALF_UP))


def num(value, T: dict) -> str:
    """A number in the language's format (Ukrainian uses a decimal comma, like the app)."""
    text = str(value)
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return text.replace(".", T["decimal"])


def load_profiles() -> dict:
    data = json.loads(PROFILES.read_text(encoding="utf-8"))
    return {p["id"]: p for p in data["profiles"]}


def load_content() -> dict:
    out = {}
    for lang in LANGS:
        out[lang] = json.loads((CONTENT / f"{lang}.json").read_text(encoding="utf-8"))
        assert out[lang]["lang"] == lang, f"{lang}.json has lang={out[lang]['lang']}"
    base = set(out[LANGS[0]]["guides"])
    for lang in LANGS:
        assert set(out[lang]["guides"]) == base == set(GUIDE_SLUGS), f"guide list differs in {lang}.json"
    return out


