UNIT_RE = re.compile(r"(\d) (°C|°F|g\b|ml\b|s\b|seconds\b)")


def keep_units(text: str) -> str:
    """Join a number and its unit with a no-break space, so "7.5 g" never wraps between them."""
    return UNIT_RE.sub("\\1\u00a0\\2", text)


