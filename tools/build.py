def page_rels() -> list[str]:
    return ["", "guides/"] + [f"guides/{s}/" for s in GUIDE_SLUGS]


def owned_paths(C: dict) -> list[str]:
    paths = [C[l]["prefix"] + r + "index.html" for l in LANGS for r in page_rels()]
    return paths + ["sitemap.xml", "robots.txt"]


def sitemap(C: dict) -> str:
    paths = [C[l]["prefix"] + r for l in LANGS for r in page_rels()]
    paths += [base + C[l]["legal"] for base in LEGAL_PAGES for l in LANGS]
    urls = "\n".join(f"  <url><loc>{SITE_URL}/{p}</loc></url>" for p in paths)
    return f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{urls}\n</urlset>\n'


def robots() -> str:
    return f"User-agent: *\nAllow: /\n\nSitemap: {SITE_URL}/sitemap.xml\n"


def build() -> dict[str, str]:
    profiles = load_profiles()
    C = load_content()
    out = {}
    for lang in LANGS:
        pre = C[lang]["prefix"]
        out[pre + "index.html"] = home(C, lang, profiles)
        out[pre + "guides/index.html"] = guides_index(C, lang, profiles)
        for slug in GUIDE_SLUGS:
            out[pre + f"guides/{slug}/index.html"] = guide(C, lang, slug, profiles)
    out["sitemap.xml"] = sitemap(C)
    out["robots.txt"] = robots()
    assert sorted(out) == sorted(owned_paths(C)), "owned paths and generated files differ"
    for rel in out:
        assert not rel.startswith(PROTECTED), f"refusing to write protected path {rel}"
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv
    files = build()
    stale = []
    for rel, text in files.items():
        target = ROOT / rel
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(rel)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    if check:
        if stale:
            print("out of date: " + ", ".join(stale), file=sys.stderr)
            return 1
        print("all generated files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
